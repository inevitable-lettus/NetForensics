"""Write the CLI reference page from the argparse parser in backend/cli.py.

The page is generated, never edited by hand, so it cannot drift from the code:

    python scripts/gen_cli_reference.py          # rewrite user-docs/reference/cli.md
    python scripts/gen_cli_reference.py --check  # exit 1 if the page is out of date (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.cli import _parser  # noqa: E402  (needs the repo root on sys.path)

TARGET = ROOT / "user-docs" / "reference" / "cli.md"

HEADER = """\
---
title: Command-line reference
---

# Command-line reference

<!-- Generated by scripts/gen_cli_reference.py from the argparse parser in
     backend/cli.py. Do not edit by hand: change the parser's help text and rerun
     the script. CI fails when this page is out of date. -->

Every command is run as `python -m backend.cli [options] <command> ...` from the
repository root. Options that apply to every command go **before** the command name.
"""


def _arguments(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in parser._actions
            if not isinstance(a, (argparse._HelpAction, argparse._SubParsersAction))]


def _row(action: argparse.Action) -> str:
    if action.option_strings:
        name = ", ".join(f"`{s}`" for s in action.option_strings)
        if action.metavar or action.nargs != 0:
            name += f" `{action.metavar or action.dest.upper()}`"
    else:
        name = f"`{action.metavar or action.dest}`"
    return f"| {name} | {(action.help or '').replace('|', '/')} |"


def _table(parser: argparse.ArgumentParser) -> list[str]:
    actions = _arguments(parser)
    if not actions:
        return ["This command takes no arguments of its own.", ""]
    return ["| Argument | Meaning |", "|---|---|", *map(_row, actions), ""]


def render() -> str:
    parser = _parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help for c in sub._choices_actions}
    lines = [HEADER, "## Global options", "", *_table(parser)]
    lines += ["## Commands", "", "| Command | What it does |", "|---|---|"]
    lines += [f"| [`{name}`](#{name}) | {helps[name]} |" for name in sub.choices]
    lines.append("")
    for name, command in sub.choices.items():
        lines += [f"## {name} {{#{name}}}", "", helps[name][0].upper() + helps[name][1:] + ".", "",
                  "```text", command.format_usage().strip(), "```", "", *_table(command)]
    epilog = parser.epilog or ""
    lines += ["## Exit codes", "", "```text", epilog.strip(), "```", "",
              "Errors print one `error: ...` line on standard error.", ""]
    return "\n".join(lines)


def main() -> int:
    page = render()
    if "--check" in sys.argv[1:]:
        if not TARGET.exists() or TARGET.read_text() != page:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run scripts/gen_cli_reference.py",
                  file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(page)
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
